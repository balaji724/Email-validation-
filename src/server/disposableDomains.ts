export function isDisposableDomain(domain: string): boolean {
  return DISPOSABLE_DOMAINS.has(domain.toLowerCase().trim());
}

export function isFreeProvider(domain: string): boolean {
  return FREE_EMAIL_PROVIDERS.has(domain.toLowerCase().trim());
}

export function isRoleBasedAccount(localPart: string): boolean {
  const clean = localPart.toLowerCase().trim().replace(/[\.\+\-\_]/g, '');
  if (ROLE_BASED_PREFIXES.has(clean)) return true;
  // Also check if any exact match with separator
  const parts = localPart.toLowerCase().trim().split(/[\.\+\-\_]/);
  return parts.some(p => ROLE_BASED_PREFIXES.has(p));
}
